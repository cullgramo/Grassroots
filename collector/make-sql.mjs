// Builds one SQL file that loads everything the public-page readers found and could place on the map.
// Usage: node collector/make-sql.mjs <out.sql> <left-out.csv>
// Used while the daily run is not switched on. Reads the database only to avoid showing a game twice.
import { readFileSync, writeFileSync } from 'node:fs';
import { SOURCES, collect } from './look.mjs';
import { groundKey, loadGrounds } from './lib/grounds.mjs';
import { getJson, irishTimeToIso, norm } from './lib/util.mjs';

const [, , sqlPath, leftOutPath] = process.argv;
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const grounds = loadGrounds();
const words = (t) => norm(t).split(' ').filter((w) => w.length >= 5);

// Fixtures already in the app from hand-loaded files; the reader's copy replaces them.
let existing = [];
try {
  existing = await getJson('https://dxkurwkmbnireaptcsbd.supabase.co/rest/v1/fixtures?select=sport_id,home_team,away_team,starts_at,source,source_ref&limit=5000&apikey=' + process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY, 0);
} catch { /* without it, nothing is replaced */ }

const fixtures = [];
const leftOut = [];
const replaced = new Set();
const live = {};
for (const [key, source] of Object.entries(SOURCES)) {
  const { upcoming, problems } = await collect(source);
  // Only tidy away a source's old fixtures when every one of its pages was read.
  if (problems.length === 0 && upcoming.length > 0) live[key] = [];
  for (const f of upcoming) {
    const leave = (reason) => leftOut.push({ source: source.name, date: f.date, time: f.time ?? '', home: f.home, away: f.away, venue: f.venue, reason });
    if (!f.venue) { leave('No ground given'); continue; }
    if (!f.startsAt && !f.time) { leave('Start time not set yet'); continue; }
    const ground = grounds[groundKey(f)];
    if (!ground) { leave('Ground not placed on the map yet'); continue; }
    const startsAt = f.startsAt ?? irishTimeToIso(f.date, f.time);
    const ref = `${key}-${f.ref}`;
    live[key]?.push(ref);
    for (const e of existing) {
      if (e.source !== 'admin' || e.sport_id !== f.sport || e.starts_at.slice(0, 10) !== startsAt.slice(0, 10)) continue;
      const theirs = [...words(e.home_team ?? ''), ...words(e.away_team ?? '')];
      if (words(f.home).some((w) => theirs.includes(w)) && words(f.away).some((w) => theirs.includes(w))) replaced.add(e.source_ref);
    }
    fixtures.push({ ...f, source: key, ref, startsAt, ground });
  }
}

const venues = [...new Map(fixtures.map((f) => [`${f.ground.name}|${f.ground.county}`, f.ground])).values()];
const sql = [
  `-- Fixtures read from public pages on ${new Date().toISOString().slice(0, 10)}: ${fixtures.length} fixtures at ${venues.length} grounds.`,
  '-- Generated by collector/make-sql.mjs. Safe to run twice.',
  '',
  readFileSync(new URL('../supabase/migrations/0003_open_sources.sql', import.meta.url), 'utf8').trim(),
  '',
  'insert into public.venues (name, county, latitude, longitude) values',
  venues.map((v) => `  (${q(v.name)}, ${q(v.county)}, ${v.latitude}, ${v.longitude})`).join(',\n'),
  'on conflict (name, county) do nothing;',
  '',
  'insert into public.fixtures',
  '  (sport_id, level, category, competition, home_team, away_team, venue_id, starts_at, ticketed, approval, source, source_ref, source_url)',
  "select s.sport_id, s.level, s.category, s.competition, s.home_team, s.away_team, v.id, s.starts_at::timestamptz, false, 'approved', s.source, s.source_ref, s.source_url",
  'from (values',
  fixtures.map((f) => `  (${q(f.source)}, ${q(f.ref)}, ${q(f.sport)}, ${q(f.level)}, ${q(f.category)}, ${q(f.competition)}, ${q(f.home)}, ${q(f.away)}, ${q(f.ground.name)}, ${q(f.ground.county)}, ${q(f.startsAt)}, ${q(f.url)})`).join(',\n'),
  ') as s (source, source_ref, sport_id, level, category, competition, home_team, away_team, venue_name, venue_county, starts_at, source_url)',
  'join public.venues v on v.name = s.venue_name and v.county = s.venue_county',
  'on conflict (source, source_ref) do update set starts_at = excluded.starts_at, competition = excluded.competition, venue_id = excluded.venue_id,',
  '  home_team = excluded.home_team, away_team = excluded.away_team;',
  '',
  '-- A game no longer on its source page has been moved or called off, so it comes off the app.',
  ...Object.entries(live).filter(([, refs]) => refs.length).map(([key, refs]) =>
    `delete from public.fixtures where source = ${q(key)} and starts_at > now() and source_ref not in (${refs.map(q).join(', ')});`),
  '',
  ...(replaced.size ? ['-- The same games loaded earlier from a spreadsheet; the versions above replace them.',
    `delete from public.fixtures where source = 'admin' and source_ref in (${[...replaced].map(q).join(', ')});`, ''] : []),
].join('\n');
writeFileSync(sqlPath, sql);

const cell = (v) => (/[",\n]/.test(v) ? `"${String(v).replace(/"/g, '""')}"` : v ?? '');
const cols = ['source', 'date', 'time', 'home', 'away', 'venue', 'reason'];
writeFileSync(leftOutPath, [cols.join(','), ...leftOut.map((r) => cols.map((c) => cell(r[c])).join(','))].join('\n') + '\n');

const tally = (list, by) => Object.entries(list.reduce((m, x) => ((m[by(x)] = (m[by(x)] ?? 0) + 1), m), {})).map(([k, n]) => `${k} ${n}`).join(', ');
console.log(`ready to load: ${fixtures.length} | left out: ${leftOut.length} | replaces ${replaced.size} hand-loaded copies`);
console.log('by source:', tally(fixtures, (f) => SOURCES[f.source].name));
console.log('by county:', tally(fixtures, (f) => f.ground.county));
console.log('left out:', tally(leftOut, (r) => `${r.source}: ${r.reason}`));
