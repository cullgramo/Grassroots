// Builds supabase/seed.sql from the app's sample data, so the two never drift apart.
// Usage: node scripts/make-seed.js
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

function load(file) {
  const src = fs.readFileSync(path.join(__dirname, '..', file), 'utf8');
  const js = ts.transpileModule(src, { compilerOptions: { module: 'commonjs', target: 'es2020' } }).outputText;
  const mod = { exports: {} };
  new Function('module', 'exports', 'require', js)(mod, mod.exports, () => ({}));
  return mod.exports;
}

const { SPORTS } = load('constants/sports.ts');
const { fixtures } = load('data/fixtures.ts');
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const today = new Date();
today.setHours(0, 0, 0, 0);

const venues = new Map();
for (const f of fixtures) venues.set(`${f.venue}|${f.county}`, f);

const out = [
  '-- Sample data for Grassroots. Generated by scripts/make-seed.js; do not edit by hand.',
  '-- Invented fixtures at real venues, dated relative to the day this is run. Safe to re-run.',
  '',
  'insert into public.sports (id, name, sport_group, shape, color, start_word, sort_order) values',
  SPORTS.map((s, i) => `  (${q(s.id)}, ${q(s.name)}, ${q(s.group)}, ${q(s.shape)}, ${q(s.color)}, ${q(s.startWord)}, ${i})`).join(',\n'),
  'on conflict (id) do update set name = excluded.name, sport_group = excluded.sport_group, shape = excluded.shape,',
  '  color = excluded.color, start_word = excluded.start_word, sort_order = excluded.sort_order;',
  '',
  'insert into public.venues (name, county, latitude, longitude) values',
  [...venues.values()].map((f) => `  (${q(f.venue)}, ${q(f.county)}, ${f.latitude}, ${f.longitude})`).join(',\n'),
  'on conflict (name, county) do update set latitude = excluded.latitude, longitude = excluded.longitude;',
  '',
  'insert into public.fixtures',
  '  (sport_id, level, competition, home_team, away_team, title, venue_id, starts_at, ticketed, ticket_url, approval, source, source_ref)',
  'select s.sport_id, s.level, s.competition, s.home_team, s.away_team, s.title, v.id,',
  "  (((now() at time zone 'Europe/Dublin')::date + s.day_offset) + s.start_time) at time zone 'Europe/Dublin',",
  "  s.ticketed, s.ticket_url, 'approved', 'admin', s.source_ref",
  'from (values',
  fixtures
    .map((f) => {
      const d = new Date(f.startsAt);
      const day = Math.round((new Date(d).setHours(0, 0, 0, 0) - today) / 86400000);
      const time = `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`;
      const level = f.level === 'Local' ? 'local' : 'top';
      return `  (${q('sample-' + f.id)}, ${q(f.sport)}, ${q(level)}, ${q(f.competition)}, ${q(f.homeTeam)}, ${q(f.awayTeam)}, ${q(f.title)}, ${q(f.venue)}, ${q(f.county)}, ${day}, time ${q(time)}, ${f.ticketed}, ${q(f.ticketUrl)})`;
    })
    .join(',\n'),
  ') as s (source_ref, sport_id, level, competition, home_team, away_team, title, venue_name, venue_county, day_offset, start_time, ticketed, ticket_url)',
  'join public.venues v on v.name = s.venue_name and v.county = s.venue_county',
  'on conflict (source, source_ref) do update set starts_at = excluded.starts_at, ticketed = excluded.ticketed, ticket_url = excluded.ticket_url;',
  '',
];
fs.writeFileSync(path.join(__dirname, '..', 'supabase', 'seed.sql'), out.join('\n'));
console.log(`Wrote ${SPORTS.length} sports, ${venues.size} venues, ${fixtures.length} fixtures.`);
